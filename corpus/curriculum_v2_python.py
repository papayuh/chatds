#!/usr/bin/env python3
"""R4 curriculum v2: python-category recipe families.

Every one of the 50 python suite items (py-001..py-050) is targeted by a
family that carries `suite_bindings`, so `curriculum_v2.py --check-suite`
can instantiate the family's answer with the suite item's own identifiers
and prove the result passes that item's accept/reject/AST rules.

R5 rewrite. Two things changed after R4 scored 15/50 on python:

1. GRAMMAR. R4 only ever trained an imperative core ("get the largest value
   in xs"). Two thirds of the suite is phrased as a NOUN PHRASE ("...for the
   largest value in the list xs") or a THIRD-PERSON VERB PHRASE ("...that
   reverses the list xs"), and the model had never seen either, so it picked
   the wrong operation. Every family now carries >=4 imperative, >=4 `np:`
   and >=4 `vp3:` cores, and one dev core of each form; the framework picks
   the wrapper set from the tag.

2. PLAINNESS. R4's cores were deliberately ornate ("reach into d and read
   whatever sits under k"). They are now mostly the words an ordinary person
   uses, which is what the suite uses. The contamination filter -- not
   self-restraint -- is what keeps the suite out of the training set: every
   record goes through offline_python.filter_pairs (exact prompt, 8-gram,
   Jaccard >= 0.8), so a phrasing sharing up to seven consecutive words with
   a suite prompt survives and anything closer is dropped, per record.
"""
